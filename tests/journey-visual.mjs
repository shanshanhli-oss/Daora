import {chromium} from 'playwright';
import {mkdir} from 'node:fs/promises';
import { chooseLondon } from './place.mjs';
const base=process.env.TEST_URL||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'/usr/bin/google-chrome',args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
await mkdir('screenshots',{recursive:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1,reducedMotion:'reduce'});
 page.setDefaultTimeout(60000);const errors=[];
 page.on('pageerror',e=>errors.push('page:'+e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 const pin=()=>page.evaluate(()=>{const s=window.daora.getScene();s.tick();s.renderer.setAnimationLoop(null);});
 await page.goto(base,{waitUntil:'networkidle',timeout:60000});
 await page.waitForSelector('#landing:not(.hidden)');
 await page.waitForTimeout(600);
 await pin();
 await page.screenshot({path:'screenshots/welcome.png',timeout:60000});
 await page.locator('[name="birthDate"]').fill('1998-06-18');
 await page.locator('[name="birthTime"]').fill('07:30');
 await chooseLondon(page);
 await page.locator('#birth-form button[type="submit"]').click();
 await page.waitForSelector('#pillars-result:not(.hidden)');
 await page.screenshot({path:'screenshots/pillars.png',timeout:60000});
 await page.locator('[data-action="confirm-entry"]').click();
 await page.waitForFunction(()=>window.daoraDiagnostics()?.entered);
 await page.waitForTimeout(400);
 await page.evaluate(()=>{
  const s=window.daora.getScene();
  s.transition=null;
  s.controls.enabled=true;
  s.controls.minAzimuthAngle=-Infinity;
  s.controls.maxAzimuthAngle=Infinity;
  s.controls.minPolarAngle=0.2;
  s.controls.maxPolarAngle=Math.PI*0.48;
  s.camera.position.set(0.35,1.62,0.15);
  s.controls.target.set(-1.15,1.2,-4.2);
  s.camera.lookAt(s.controls.target);
  s.controls.update();
  document.querySelector('#toast')?.classList.remove('visible');
  document.querySelector('#room-ui').classList.add('immersive');
 });
 await pin();
 await page.screenshot({path:'screenshots/wall-door.png',timeout:60000});
 await page.evaluate(()=>{document.querySelector('#room-ui').classList.remove('immersive');window.daora.enterJourney();});
 await page.waitForSelector('#journey-hud:not(.hidden)');
 await page.waitForTimeout(300);
 await pin();
 await page.screenshot({path:'screenshots/inner-journey.png',timeout:60000});
 console.log('shots',['screenshots/welcome.png','screenshots/pillars.png','screenshots/wall-door.png','screenshots/inner-journey.png']);
 console.log('errors',errors);
 if(errors.length)process.exitCode=1;
} finally {await browser.close();}
