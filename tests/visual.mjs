import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'/usr/bin/google-chrome',args:['--no-sandbox','--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
await page.goto('http://127.0.0.1:5173',{waitUntil:'networkidle',timeout:60000});
await page.waitForSelector('#landing:not(.hidden)',{timeout:60000});
await page.waitForTimeout(2500);
await page.screenshot({path:'screenshots/01-landing-first.png'});
console.log('landing diagnostics',await page.evaluate(()=>window.daoraDiagnostics?.()));
await page.locator('#birth-form button[type="submit"]').click();
await page.waitForTimeout(5000);
await page.screenshot({path:'screenshots/02-room-first.png'});
console.log('room diagnostics',await page.evaluate(()=>window.daoraDiagnostics?.()));
console.log('errors',errors);
await fs.writeFile('screenshots/errors-first.json',JSON.stringify(errors,null,2));
await browser.close();
